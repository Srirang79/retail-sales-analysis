"""Retail sales analysis: load the CSV into SQLite, run the SQL files, write RESULTS.md.

Usage:  python analysis.py
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).parent
CSV = ROOT / "data" / "retail_sales_dataset.csv"
SQL = ROOT / "sql"

RENAMES = {
    "Transaction ID": "transaction_id",
    "Date": "sale_date",
    "Customer ID": "customer_id",
    "Gender": "gender",
    "Age": "age",
    "Product Category": "category",
    "Quantity": "quantity",
    "Price per Unit": "unit_price",
    "Total Amount": "total_amount",
}


def load_staging(con: sqlite3.Connection) -> None:
    df = pd.read_csv(CSV).rename(columns=RENAMES)
    df["sale_date"] = pd.to_datetime(df["sale_date"], format="%m/%d/%Y").dt.strftime("%Y-%m-%d")
    df.to_sql("retail_staging", con, index=False, if_exists="replace")


def named_queries(path: Path) -> list[tuple[str, str]]:
    text = path.read_text()
    parts = re.split(r"^-- name:\s*(\w+)\s*$", text, flags=re.M)
    return [(parts[i], parts[i + 1].strip().rstrip(";")) for i in range(1, len(parts), 2)]


def run_all() -> dict[str, pd.DataFrame]:
    con = sqlite3.connect(":memory:")
    load_staging(con)
    con.executescript((SQL / "01_schema.sql").read_text())
    results = {}
    for file in ("02_quality_checks.sql", "03_analysis.sql"):
        for name, query in named_queries(SQL / file):
            results[name] = pd.read_sql_query(query, con)
    con.close()
    return results


def to_markdown(results: dict[str, pd.DataFrame]) -> str:
    out = ["# Results", "", "Generated by `python analysis.py` from `sql/`.", ""]
    for name, df in results.items():
        out += [f"## {name.replace('_', ' ')}", "", df.to_markdown(index=False), ""]
    return "\n".join(out)


if __name__ == "__main__":
    res = run_all()
    (ROOT / "RESULTS.md").write_text(to_markdown(res))
    for name, df in res.items():
        print(f"\n== {name} ==")
        print(df.to_string(index=False))
